-- Tabla de solicitudes de interés. Se ejecuta al iniciar; "if not exists" evita recrearla.
create table if not exists solicitudes (
    id             bigint generated by default as identity primary key,
    usuario_id     varchar(64)  not null,
    tipo           varchar(30)  not null,
    monto          integer,
    fecha_contacto date         not null,
    mensaje        varchar(500) not null,
    creada_en      timestamptz  not null
);

create index if not exists idx_solicitudes_usuario on solicitudes (usuario_id);

-- Supabase expone las tablas del esquema public por su API web.
-- Con RLS activo y sin políticas, esa API no puede leer ni escribir nada;
-- solo el microservicio, que se conecta como dueño de la base.
alter table solicitudes enable row level security;
