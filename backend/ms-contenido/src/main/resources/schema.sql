-- Programas de formación de la Escuela Jan Van Dijk y productos del taller Alba Lab.
-- "if not exists" evita recrear las tablas al reiniciar.
create table if not exists programas (
    id          bigint generated by default as identity primary key,
    nombre      varchar(80)  not null,
    descripcion varchar(500) not null,
    duracion    varchar(40)  not null,
    cupos       integer      not null check (cupos >= 0)
);

create table if not exists productos (
    id          bigint generated by default as identity primary key,
    nombre      varchar(80)  not null,
    descripcion varchar(500) not null,
    precio      integer      not null check (precio > 0),
    stock       integer      not null check (stock >= 0)
);

-- Solo el microservicio accede a las tablas (ver ms-solicitudes/schema.sql)
alter table programas enable row level security;
alter table productos enable row level security;

